#!/usr/bin/env python3
"""Rasterise ASCII 32..126 into anti-aliased alpha bitmaps -> src/font_data.c
Fonts: Inter (OFL) for the UI, DejaVu Sans Mono for terminal/notepad."""
from PIL import Image, ImageDraw, ImageFont
import sys

INTER = "/usr/share/fonts/opentype/inter/Inter-%s.otf"
MONO = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
FONTS = [  # name, path, px, fixed cell width (0 = proportional)
    ("ui",    INTER % "Regular",  13, 0),
    ("ui_b",  INTER % "SemiBold", 13, 0),
    ("small", INTER % "Regular",  11, 0),
    ("title", INTER % "Regular",  20, 0),
    ("big",   INTER % "Light",    32, 0),
    ("mono",  MONO,               13, 8),
]

out = ['/* generated by tools/gen_font.py - do not edit */', '#include "os.h"', '']
for name, path, px, fixed in FONTS:
    f = ImageFont.truetype(path, px)
    asc, desc = f.getmetrics()
    bits, adv, gw, gh, gx, gy, goff = bytearray(), [], [], [], [], [], []
    for c in range(32, 127):
        ch = chr(c)
        x0, y0, x1, y1 = f.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        goff.append(len(bits))
        if w and h and ch != " ":
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-x0, -y0), ch, font=f, fill=255, anchor="ls")
            bits += bytes(im.tobytes())
        else:
            w = h = 0
        gw.append(w); gh.append(h); gx.append(x0); gy.append(y0 + asc)
        adv.append(fixed * 16 if fixed else round(f.getlength(ch) * 16))
    def arr(t, n, v):
        return "static const %s f_%s_%s[] = {%s};" % (t, name, n, ",".join("%d" % x for x in v))
    out.append(arr("uint8_t", "bits", bits))
    out.append(arr("uint16_t", "adv", adv))
    out.append(arr("uint8_t", "gw", gw)); out.append(arr("uint8_t", "gh", gh))
    out.append(arr("int8_t", "gx", gx)); out.append(arr("int8_t", "gy", gy))
    out.append(arr("uint32_t", "off", goff))
    out.append("const Font font_%s = {%d,%d,%d,f_%s_adv,f_%s_gw,f_%s_gh,f_%s_gx,f_%s_gy,f_%s_off,f_%s_bits};\n"
               % (name, asc + desc, asc, fixed, *([name] * 7)))
    print("%-6s %2dpx  h=%d  %6d bytes" % (name, px, asc + desc, len(bits)), file=sys.stderr)
open("src/font_data.c", "w").write("\n".join(out))
